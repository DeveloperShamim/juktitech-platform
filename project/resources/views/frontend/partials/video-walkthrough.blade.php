<script>
document.addEventListener('DOMContentLoaded', function() {
    const playBtn = document.getElementById('openWalkthroughVideoBtn');
    const modal = document.getElementById('walkthroughModal');
    const closeBtn = document.getElementById('closeWalkthroughModalBtn');
    const backdrop = document.getElementById('closeWalkthroughModalBackdrop');
    const iframe = document.getElementById('walkthroughIframe');

    function openModal() {
        if (!modal || !iframe) return;
        const videoSrc = iframe.getAttribute('data-src');
        iframe.setAttribute('src', videoSrc);
        modal.classList.add('is-active');
        document.body.style.overflow = 'hidden';
    }

    function closeModal() {
        if (!modal || !iframe) return;
        iframe.setAttribute('src', '');
        modal.classList.remove('is-active');
        document.body.style.overflow = '';
    }

    if (playBtn) playBtn.addEventListener('click', openModal);
    if (closeBtn) closeBtn.addEventListener('click', closeModal);
    if (backdrop) backdrop.addEventListener('click', closeModal);

    document.addEventListener('keydown', function(e) {
        if (e.key === 'Escape' && modal && modal.classList.contains('is-active')) {
            closeModal();
        }
    });
});
</script>
